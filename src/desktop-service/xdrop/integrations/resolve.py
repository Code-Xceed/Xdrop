"""
DaVinci Resolve integration: a launcher script dropped into Resolve's `Scripts/Utility` folder.

Resolve needs no package format, no signing and no installer — it scans its script folders on
startup and lists whatever it finds under **Workspace → Scripts → Utility**. The only real
decision is *which* folder:

- the **per-user** folder, which any user can write without administrator rights, and
- the **all-users** folder (`C:\\ProgramData\\...` on Windows, `/Library/...` on macOS), which
  normally needs elevation.

The default is the per-user folder. That is the difference between "install the Resolve
integration" being a button with no follow-up prompt and being a support ticket, so the
all-users folder is only used when explicitly asked for (`scope="system"`).

When a write really is denied, the result says so plainly — the path that was attempted, that
administrator rights are the blocker, and that the per-user install is the way around it.
Nothing is silently swallowed.
"""

from __future__ import annotations

import errno
import sys
from pathlib import Path
from typing import Dict, List, Optional

from xdrop.logger import resolve_logger

from .paths import (
    LAUNCHER_NAME,
    LEGACY_LAUNCHER_NAME,
    SERVICE_URL,
    SYSTEM_SCOPE,
    USER_SCOPE,
    HostPlatformPaths,
    detect,
    desktop_service_root,
    repo_root,
    resolve_script_dir,
    resolve_script_dirs,
)
from .results import InstallResult

#: Environment variables that make a menu-invoked script work when it lives outside the
#: `Scripts/` tree. Not needed for the normal install, recorded in the launcher for
#: completeness so a user who moves the file is not stranded.
_SCRIPT_ENV_HINT = (
    "RESOLVE_SCRIPT_API / RESOLVE_SCRIPT_LIB / PYTHONPATH are only required when the script "
    "is launched from outside Resolve's Scripts folder."
)


def build_resolve_script_content(
    repo_root_path: Optional[Path] = None,
    service_root: Optional[Path] = None,
    python_exe: Optional[str] = None,
) -> str:
    """Generates the launcher script.

    The script is deliberately self-contained — it imports only the standard library — because
    it runs inside Resolve's interpreter, which is not the user's, and which may not have
    Xdrop's dependencies. Its jobs are: check whether the Xdrop service is up, start it
    headlessly if not, then hand the user to the companion UI.
    """
    root = repo_root_path or repo_root()
    service = service_root or desktop_service_root()
    py_exe = python_exe or sys.executable

    run_bat = root / "run.bat"
    run_sh = root / "run.sh"
    main_py = service / "main.py"
    py_posix = Path(py_exe).as_posix() if py_exe else sys.executable
    main_posix = main_py.as_posix()
    bat_posix = run_bat.as_posix()
    sh_posix = run_sh.as_posix()

    return f'''#!/usr/bin/env python
"""
Xdrop - DaVinci Resolve Integration Launcher

Generated by Xdrop. Appears under Workspace -> Scripts -> Utility -> {LAUNCHER_NAME}.
Safe to delete; re-install any time from Xdrop's Settings page.

Runs inside Resolve's bundled Python. Standard library only, on purpose.
{_SCRIPT_ENV_HINT}
"""

import os
import subprocess
import sys
import time
import urllib.request
import webbrowser

PANEL_URL = "{SERVICE_URL}?host=resolve"
HEALTH_URL = "{SERVICE_URL}/api/health"

PYTHON_EXE = {py_posix!r}
MAIN_PY = {main_posix!r}
RUN_BAT = {bat_posix!r}
RUN_SH = {sh_posix!r}


def is_service_running():
    try:
        with urllib.request.urlopen(HEALTH_URL, timeout=1.5) as response:
            return response.getcode() == 200
    except Exception:
        return False


def silent_launch_flags():
    flags = 0
    if sys.platform == "win32":
        if hasattr(subprocess, "CREATE_NO_WINDOW"):
            flags |= subprocess.CREATE_NO_WINDOW
        flags |= getattr(subprocess, "DETACHED_PROCESS", 0x00000008)
    return flags


def start_service():
    """Starts the Xdrop engine with no visible window and no console."""
    flags = silent_launch_flags()

    if os.path.isfile(MAIN_PY):
        interpreter = PYTHON_EXE if os.path.isfile(PYTHON_EXE) else sys.executable
        kwargs = {{
            "cwd": os.path.dirname(MAIN_PY),
            "stdin": subprocess.DEVNULL,
            "stdout": subprocess.DEVNULL,
            "stderr": subprocess.DEVNULL,
        }}
        if sys.platform == "win32":
            kwargs["creationflags"] = flags
        else:
            kwargs["start_new_session"] = True
        try:
            subprocess.Popen([interpreter, MAIN_PY], **kwargs)
            return True
        except Exception as error:
            print(f"[Xdrop] Automatic start failed: {{error}}")

    launcher = RUN_BAT if sys.platform == "win32" else RUN_SH
    if os.path.isfile(launcher):
        try:
            if sys.platform == "win32":
                subprocess.Popen(
                    ["cmd.exe", "/c", launcher],
                    cwd=os.path.dirname(launcher),
                    creationflags=flags,
                    stdin=subprocess.DEVNULL,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
            else:
                subprocess.Popen(
                    ["bash", launcher],
                    cwd=os.path.dirname(launcher),
                    stdin=subprocess.DEVNULL,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    start_new_session=True,
                )
            return True
        except Exception as error:
            print(f"[Xdrop] Automatic start failed: {{error}}")

    return False


def open_desktop_window(url):
    """Opens a standalone desktop application window (no browser tabs, address bar, or bookmarks)."""
    if sys.platform == "win32":
        candidates = [
            os.path.expandvars("%ProgramFiles(x86)%/Microsoft/Edge/Application/msedge.exe"),
            os.path.expandvars("%ProgramFiles%/Microsoft/Edge/Application/msedge.exe"),
            os.path.expandvars("%LocalAppData%/Microsoft/Edge/Application/msedge.exe"),
            os.path.expandvars("%ProgramFiles%/Google/Chrome/Application/chrome.exe"),
            os.path.expandvars("%ProgramFiles(x86)%/Google/Chrome/Application/chrome.exe"),
            os.path.expandvars("%LocalAppData%/Google/Chrome/Application/chrome.exe"),
            os.path.expandvars("%ProgramFiles%/BraveSoftware/Brave-Browser/Application/brave.exe"),
        ]
        for exe in candidates:
            if os.path.isfile(exe):
                try:
                    subprocess.Popen([exe, f"--app={{url}}", "--window-size=390,640", "--app-id=Xdrop"])
                    return True
                except Exception:
                    pass
    elif sys.platform == "darwin":
        mac_apps = [
            "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
            "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
            "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
            os.path.expanduser("~/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"),
        ]
        for app in mac_apps:
            if os.path.isfile(app):
                try:
                    subprocess.Popen([app, f"--app={{url}}", "--window-size=390,640"])
                    return True
                except Exception:
                    pass
    else:
        import shutil
        for name in ("google-chrome", "google-chrome-stable", "chromium", "chromium-browser", "microsoft-edge", "brave"):
            bin_path = shutil.which(name)
            if bin_path:
                try:
                    subprocess.Popen([bin_path, f"--app={{url}}", "--window-size=390,640"])
                    return True
                except Exception:
                    pass
    try:
        webbrowser.open(url)
        return True
    except Exception as error:
        print(f"[Xdrop] Could not open interface: {{error}}")
        return False


def main():
    print("[Xdrop] Connecting to the Xdrop engine...")

    if not is_service_running():
        print("[Xdrop] Engine offline - starting it in the background...")
        if start_service():
            for _ in range(16):
                if is_service_running():
                    print("[Xdrop] Engine is online.")
                    break
                time.sleep(0.5)
        else:
            print("[Xdrop] Could not start the engine automatically.")
            print(f"[Xdrop] Start it manually, then open {{PANEL_URL}}")

    print(f"[Xdrop] Opening native panel window: {{PANEL_URL}}")
    open_desktop_window(PANEL_URL)


if __name__ == "__main__":
    main()
'''


def _write_launchers(target_dir: Path, content: str) -> List[str]:
    """Writes the current and legacy launcher filenames. Returns the files written."""
    written: List[str] = []
    for name in (f"{LAUNCHER_NAME}.py", f"{LEGACY_LAUNCHER_NAME}.py"):
        path = target_dir / name
        path.write_text(content, encoding="utf-8")
        written.append(str(path))
    return written


def _is_permission_error(exc: BaseException) -> bool:
    return isinstance(exc, PermissionError) or (
        isinstance(exc, OSError) and exc.errno in (errno.EACCES, errno.EPERM)
    )


def install_resolve_script(
    paths: Optional[HostPlatformPaths] = None,
    scope: str = USER_SCOPE,
    content: Optional[str] = None,
) -> InstallResult:
    """Installs the Resolve launcher into the requested scope. Default: per-user, no admin."""
    paths = paths or detect()
    label = "DaVinci Resolve"
    target_dir = resolve_script_dir(paths, scope)
    target_file = target_dir / f"{LAUNCHER_NAME}.py"
    script = content if content is not None else build_resolve_script_content()
    per_user_dir, all_users_dir = resolve_script_dirs(paths)

    try:
        target_dir.mkdir(parents=True, exist_ok=True)
        written = _write_launchers(target_dir, script)
    except OSError as exc:
        denied = _is_permission_error(exc)
        if denied:
            message = (
                f"Administrator rights are required to write {target_dir}. "
                f"Install the script for the current user instead — that path is "
                f"{per_user_dir} and needs no elevation."
            )
        else:
            message = f"Could not write the Resolve launcher to {target_dir}: {exc}"
        resolve_logger.error("Resolve script install failed for %s: %s", target_dir, exc)
        return InstallResult(
            host="resolve",
            label=label,
            ok=False,
            message=message,
            path=str(target_dir),
            scope=scope,
            requires_admin=denied,
            details={"error": str(exc), "perUserPath": str(per_user_dir)},
        )

    # Verify by reading back: the installer's contract is that the file Resolve will scan
    # exists and contains what we intended, not that a write call returned without raising.
    try:
        on_disk = target_file.read_text(encoding="utf-8")
    except OSError as exc:
        return InstallResult(
            host="resolve",
            label=label,
            ok=False,
            message=f"Wrote {target_file} but could not read it back to verify: {exc}",
            path=str(target_file),
            scope=scope,
            details={"error": str(exc), "written": written},
        )

    verified = on_disk == script

    if not verified:
        return InstallResult(
            host="resolve",
            label=label,
            ok=False,
            message=f"{target_file} exists but does not match what Xdrop intended to write.",
            path=str(target_file),
            scope=scope,
            details={"written": written},
        )

    scope_note = (
        "for all users of this machine"
        if scope == SYSTEM_SCOPE
        else "for the current user (no administrator rights needed)"
    )
    resolve_logger.info("Installed Xdrop Resolve launcher to %s", target_file)

    return InstallResult(
        host="resolve",
        label=label,
        ok=True,
        message=(
            f"Installed {scope_note} at {target_file}. "
            "Restart DaVinci Resolve, then use Workspace → Scripts → Utility → Xdrop."
        ),
        path=str(target_file),
        scope=scope,
        restart_required=True,
        details={
            "written": written,
            "perUserPath": str(per_user_dir),
            "allUsersPath": str(all_users_dir),
        },
    )


def resolve_script_status(paths: Optional[HostPlatformPaths] = None) -> Dict[str, object]:
    """Reports every location Resolve scans, and whether Xdrop is present in any of them."""
    paths = paths or detect()
    per_user_dir, all_users_dir = resolve_script_dirs(paths)

    locations: List[Dict[str, object]] = []
    installed_at: Optional[str] = None
    found_scope: Optional[str] = None

    for scope, directory in ((USER_SCOPE, per_user_dir), (SYSTEM_SCOPE, all_users_dir)):
        present = any(
            (directory / f"{name}.py").is_file()
            for name in (LAUNCHER_NAME, LEGACY_LAUNCHER_NAME)
        )
        locations.append(
            {
                "scope": scope,
                "path": str(directory),
                "installed": present,
                "requiresAdmin": scope == SYSTEM_SCOPE,
            }
        )
        if present and installed_at is None:
            installed_at = str(directory)
            found_scope = scope

    notes: List[str] = []
    if installed_at is None:
        notes.append(
            "Not installed. Installing writes to "
            f"{per_user_dir}, which needs no administrator rights."
        )
    else:
        notes.append("Restart DaVinci Resolve so it re-scans its script folders.")

    return {
        "installed": installed_at is not None,
        "path": installed_at,
        "scope": found_scope,
        "locations": locations,
        "scriptEnvHint": _SCRIPT_ENV_HINT,
        "notes": notes,
    }
